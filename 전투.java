package rpg;

import java.util.HashMap;
import java.util.Map;

public class 전투 {
    private 캐릭터 생성된캐릭터;
    private String 마지막결과메시지 = "";
    private Map<String, 길드> 길드목록 = new HashMap<>();

    public 전투() {
        길드목록.put("모험가연합", new 길드("모험가연합"));
        길드목록.put("던전공격대", new 길드("던전공격대"));
    }

    public String get마지막결과메시지() {
        return 마지막결과메시지;
    }

    public void 캐릭터생성(String 플레이어id, String 캐릭터명, int 레벨, String 직업) {
        플레이어 플 = new 플레이어();

        if (!플.플레이어체크(플레이어id)) {
            마지막결과메시지 = "올바른 플레이어가 아닙니다.";
            return;
        }

        if ("전사".equals(직업)) {
            생성된캐릭터 = new 전사(캐릭터명, 레벨);
        } else if ("마법사".equals(직업)) {
            생성된캐릭터 = new 마법사(캐릭터명, 레벨);
        } else {
            마지막결과메시지 = "올바르지 않은 직업입니다.";
            return;
        }

        마지막결과메시지 = "캐릭터 생성 성공! [ " + 생성된캐릭터.get캐릭터명() + " / " + 직업 + " / Lv." + 생성된캐릭터.get레벨()
                + " / HP: " + 생성된캐릭터.getHP() + " / 공격력: " + 생성된캐릭터.get공격력() + " ]";
    }

    public void 몬스터공격(String 플레이어id) {
        플레이어 플 = new 플레이어();

        if (!플.플레이어체크(플레이어id)) {
            마지막결과메시지 = "플레이어 인증 실패";
            return;
        }

        if (생성된캐릭터 == null) {
            마지막결과메시지 = "먼저 캐릭터를 생성해주세요.";
            return;
        }

        if (생성된캐릭터 instanceof 전사) {
            생성된캐릭터.스킬발동();
        } else if (생성된캐릭터 instanceof 마법사) {
            생성된캐릭터.스킬발동();
        } else {
            마지막결과메시지 = "전사 또는 마법사 캐릭터가 아닙니다.";
            return;
        }

        String 스킬명 = 생성된캐릭터.get마지막스킬명();
        double 데미지 = 생성된캐릭터.get마지막데미지();

        String 등급;
        if (데미지 >= 200) {
            등급 = "S급 공격";
        } else if (데미지 >= 100) {
            등급 = "A급 공격";
        } else {
            등급 = "B급 공격";
        }

        마지막결과메시지 = "스킬 발동: " + 스킬명 + "\n가한 데미지: " + 데미지 + "\n결과: " + 등급;
    }

    public void 아이템획득(String 플레이어id, String 아이템명, String 아이템타입, int 아이템가치) {
        플레이어 플 = new 플레이어();

        if (!플.플레이어체크(플레이어id)) {
            마지막결과메시지 = "획득 실패 (플레이어 불일치)";
            return;
        }

        if (생성된캐릭터 == null) {
            마지막결과메시지 = "먼저 캐릭터를 생성해주세요.";
            return;
        }

        if (!아이템타입유효(아이템타입)) {
            마지막결과메시지 = "획득 실패 (올바르지 않은 아이템타입: 무기, 방어구, 물약만 가능)";
            return;
        }

        인벤토리 인벤 = 생성된캐릭터.get인벤토리();
        if (!인벤.아이템추가(아이템명, 아이템타입, 아이템가치)) {
            마지막결과메시지 = "획득 실패 (공간 부족)";
            return;
        }

        아이템 획득아이템 = 인벤.get마지막아이템();
        마지막결과메시지 = "아이템 획득 성공! [ " + 획득아이템.get아이템명() + " / " + 획득아이템.get타입()
                + " / 가치: " + 획득아이템.get가치() + " / 등급: " + 획득아이템.get등급()
                + " ] (인벤토리 " + 인벤.get현재개수() + "/" + 인벤.get최대용량() + ")";
    }

    public void 길드가입(String 플레이어id, String 길드명) {
        플레이어 플 = new 플레이어();

        if (!플.플레이어체크(플레이어id)) {
            마지막결과메시지 = "올바른 플레이어가 아닙니다.";
            return;
        }

        if (생성된캐릭터 == null) {
            마지막결과메시지 = "먼저 캐릭터를 생성해주세요.";
            return;
        }

        길드 길드객체 = 길드목록.get(길드명);
        if (길드객체 == null) {
            마지막결과메시지 = "가입 실패 (존재하지 않는 길드입니다.)";
            return;
        }

        if (길드객체.캐릭터가입(생성된캐릭터)) {
            마지막결과메시지 = "길드 가입 성공! [ " + 길드명 + " / 현재 인원: "
                    + 길드객체.get현재인원() + "/" + 길드객체.get최대인원() + " ]";
        } else {
            마지막결과메시지 = "길드 정원이 가득 찼습니다.";
        }
    }

    private boolean 아이템타입유효(String 아이템타입) {
        return "무기".equals(아이템타입) || "방어구".equals(아이템타입) || "물약".equals(아이템타입);
    }
}
