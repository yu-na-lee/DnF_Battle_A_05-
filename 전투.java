package rpg;

public class 전투 {
    // 상태 유지를 위해 생성된 캐릭터를 보관
    private 캐릭터 생성된캐릭터;

    public String 캐릭터생성(String 플레이어id, String 캐릭터명, int 레벨, String 직업) {
        플레이어 플 = new 플레이어();
        
        // 1. 플레이어 체크
        if (!플.플레이어체크(플레이어id)) {
            return "올바른 플레이어가 아닙니다. (인증 실패)";
        }

        // 2. 직업에 따른 캐릭터 객체 생성 및 능력치 설정
        if ("전사".equals(직업)) {
            생성된캐릭터 = new 전사(캐릭터명, 레벨);
        } else if ("마법사".equals(직업)) {
            생성된캐릭터 = new 마법사(캐릭터명, 레벨);
        } else {
            return "올바르지 않은 직업입니다.";
        }

        return "캐릭터 생성 성공! [ " + 생성된캐릭터.get캐릭터명() + " / " + 직업 + " / Lv." + 생성된캐릭터.get레벨() 
                + " / HP: " + 생성된캐릭터.getHP() + " / 공격력: " + 생성된캐릭터.get공격력() + " ]";
    }

    public String 몬스터공격(String 플레이어id) {
        플레이어 플 = new 플레이어();
        
        // 1. 플레이어 체크
        if (!플.플레이어체크(플레이어id)) {
            return "플레이어 인증 실패";
        }

        if (생성된캐릭터 == null) {
            return "먼저 캐릭터를 생성해주세요.";
        }

        // 2. 스킬 발동 (동적 바인딩)
        Object[] 결과 = 생성된캐릭터.스킬발동();
        String 스킬명 = (String) 결과[0];
        double 데미지 = (Double) 결과[1];

        // 3. 데미지 등급 판별
        String 등급;
        if (데미지 >= 200) {
            등급 = "S급 공격";
        } else if (데미지 >= 100) {
            등급 = "A급 공격";
        } else {
            등급 = "B급 공격";
        }

        return "스킬 발동: " + 스킬명 + "<br>가한 데미지: " + 데미지 + "<br>결과: <b>" + 등급 + "</b>";
    }
}